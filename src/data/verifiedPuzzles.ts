/**
 * Every puzzle in the app comes from this list. Each one is checked by
 * scripts/validate-puzzles.ts: legal position, legal solution, the solver's side
 * to move, and mates that really are mate. When this list was built, every line
 * was also checked with Stockfish 16: each solver move is the engine's best (or
 * keeps a forced mate), the first move is clearly better than any alternative,
 * and the line ends in mate or a decisive advantage.
 *
 * Game sources are the real games; the moves were replayed from the full game
 * score to reach each position.
 */
